/**
 * Generates the cellular backdrop data shared by the WebGL scene and the CSS fallback.
 *
 *   node scripts/make-backdrop.mjs
 *
 * Writes:
 *   src/components/scene/backdropData.ts   (bokeh, nuclei, ball-and-stick atoms and bonds, membrane arcs)
 *   public/backdrop.svg                    (static 1920×1200 rendering of the same field)
 *
 * Coordinates are in "view units": the visible height of the gallery view is 1, the origin
 * is the centre of the screen, x grows to the right and y grows upward. The shader and the
 * SVG both map these the same way, so the fallback matches the live scene.
 */
